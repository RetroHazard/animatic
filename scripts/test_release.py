class ChecksumTests(TempDirCase):
    def setUp(self) -> None:
        super().setUp()
        write_workspace(self.root)
        self.dist = self.tmp / "dist"
        self.dist.mkdir()
        self.win = self.dist / f"animatic-v{V0}-windows-x86_64.zip"
        self.lin = self.dist / f"animatic-v{V0}-linux-x86_64.tar.gz"
        self.win.write_bytes(b"windows archive bytes" * 100)
        self.lin.write_bytes(b"linux archive bytes" * 100)

    def checksums(self) -> tuple[int, str, str]:
        return run_cli(self.root, "checksums", "--directory", str(self.dist))

    def test_writes_sorted_sha256sums_and_replaces_stale_file(self) -> None:
        (self.dist / "SHA256SUMS").write_text("stale\n", encoding="utf-8")
        code, _, err = self.checksums()
        self.assertEqual(code, 0, err)
        expected = "".join(
            f"{hashlib.sha256(p.read_bytes()).hexdigest()}  {p.name}\n" for p in sorted([self.win, self.lin])
        )
        self.assertEqual((self.dist / "SHA256SUMS").read_bytes(), expected.encode())
        self.assertEqual(sorted(p.name for p in self.dist.iterdir()),
                         sorted([self.win.name, self.lin.name, "SHA256SUMS"]))
        self.assertEqual(self.checksums()[0], 0)  # idempotent

    def assertRefused(self) -> None:
        stale = self.dist / "SHA256SUMS"
        stale.write_text("stale\n", encoding="utf-8")
        before = sorted(p.name for p in self.dist.iterdir())
        self.assertNotEqual(self.checksums()[0], 0)
        self.assertEqual(stale.read_text(encoding="utf-8"), "stale\n")
        self.assertEqual(sorted(p.name for p in self.dist.iterdir()), before)

    def test_missing_archive_is_refused(self) -> None:
        self.lin.unlink()
        self.assertRefused()

    def test_unexpected_or_wrong_version_artifacts_are_refused(self) -> None:
        (self.dist / "notes.txt").write_text("x", encoding="utf-8")
        self.assertRefused()
        (self.dist / "notes.txt").unlink()
        (self.dist / "animatic-v2026.10.0-linux-x86_64.tar.gz").write_bytes(b"old")
        self.assertRefused()

    def test_empty_archive_is_refused(self) -> None:
        self.win.write_bytes(b"")
        self.assertRefused()

    def test_symlinked_archive_is_refused(self) -> None:
        real = self.tmp / "real.tar.gz"
        real.write_bytes(b"real")
        self.lin.unlink()
        try:
            self.lin.symlink_to(real)
        except (OSError, NotImplementedError):
            self.skipTest("symlinks unavailable")
        self.assertRefused()


