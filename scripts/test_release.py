def write(root: Path, rel: str, text: str) -> None:
    path = root / rel
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text, encoding="utf-8", newline="\n")


def git(root: Path, *args: str) -> str:
    proc = subprocess.run(
        ["git", "-c", "commit.gpgsign=false", "-c", "tag.gpgsign=false", "-c", "core.autocrlf=false",
         "-C", str(root), *args],
        capture_output=True, text=True, encoding="utf-8",
    )
    assert proc.returncode == 0, f"git {args} failed: {proc.stderr}"
    return proc.stdout


def write_workspace(root: Path, *, changelog: str = CHANGELOG) -> None:
    write(root, "Cargo.toml", ROOT_MANIFEST)
    write(root, "crates/relkit-core/Cargo.toml", CORE_MANIFEST)
    write(root, "crates/relkit-net/Cargo.toml", NET_MANIFEST)
    write(root, "crates/relkit-app/Cargo.toml", APP_MANIFEST)
    write(root, "Cargo.lock", LOCK)
    write(root, "CHANGELOG.md", changelog)
    write(root, "LICENSE", "Synthetic license text\n")
    write(root, "README.md", "# Synthetic readme\n")
    for rel, text in DOCS.items():
        write(root, rel, text)


def run_cli(root: Path, *args: str) -> tuple[int, str, str]:
    out, err = io.StringIO(), io.StringIO()
    with contextlib.redirect_stdout(out), contextlib.redirect_stderr(err):
        code = release.main(["--root", str(root), *args])
    return code, out.getvalue(), err.getvalue()


def snapshot(root: Path) -> dict[str, bytes]:
    return {
        p.relative_to(root).as_posix(): p.read_bytes()
        for p in sorted(root.rglob("*"))
        if p.is_file() and ".git" not in p.relative_to(root).parts
    }


def section(changelog: str, title: str) -> str:
    """Text of one '## ' section (heading included) from a changelog."""
    for part in re.split(r"(?m)^(?=## )", changelog):
        if re.match(rf"## {re.escape(title)}(\s|$)", part):
            return part
    raise AssertionError(f"no section {title!r}")


class TempDirCase(unittest.TestCase):
    def setUp(self) -> None:
        tmp = tempfile.TemporaryDirectory(ignore_cleanup_errors=True)
        self.addCleanup(tmp.cleanup)
        self.tmp = Path(tmp.name)
        self.root = self.tmp / "repo"
        self.root.mkdir()


class GitCase(TempDirCase):
    """A git-backed synthetic workspace with one commit."""

    def setUp(self) -> None:
        super().setUp()
        if not HAVE_GIT:
            self.skipTest("git is not available")
        write_workspace(self.root)
        git(self.root, "init", "-q")
        git(self.root, "symbolic-ref", "HEAD", "refs/heads/main")
        git(self.root, "add", "-A")
        git(self.root, "commit", "-q", "-m", "chore: initial scaffolding")

    def commit(self, subject: str) -> None:
        git(self.root, "commit", "-q", "--allow-empty", "-m", subject)

    def prepare(self, version: str, today: dt.date = NOV) -> release.PrepareResult:
        return release.prepare(self.root, version, today=today)

    def release(self, version: str, today: dt.date = NOV) -> None:
        self.prepare(version, today)
        git(self.root, "add", "-A")
        git(self.root, "commit", "-q", "-m", f"chore(release): {version}")
        git(self.root, "tag", f"v{version}")

    def changelog(self) -> str:
        return (self.root / "CHANGELOG.md").read_text(encoding="utf-8")

    def assertRejected(self, version: str, today: dt.date = NOV, message: str | None = None) -> None:
        before = snapshot(self.root)
        with self.assertRaises(release.ReleaseError, msg=version) as ctx:
            self.prepare(version, today)
        self.assertEqual(snapshot(self.root), before, f"files mutated by rejected {version}")
        if message:
            self.assertIn(message, str(ctx.exception))


class VersionTests(unittest.TestCase):
    def test_accepts_calver_with_optional_prerelease(self) -> None:
        for good in ("2000.1.0", "2026.11.0", "2026.12.31", "9999.12.0", "2026.11.0-rc.1", "2026.1.0-0.3.7",
                     "2026.1.0-alpha-1"):
            self.assertEqual(release.parse_version(good).text, good)

    def test_rejects_non_calver_and_metadata(self) -> None:
        for bad in ("1.0.0", "1999.12.0", "2026.0.0", "2026.13.0", "2026.05.0", "2026.11", "2026.11.00",
                    "2026.11.0+build", "2026.11.0-rc.1+build", "v2026.11.0", "2026.11.0-", "2026.11.0-01",
                    "2026.11.0-rc..1", "", " 2026.11.0", "2026.11.0\n", "10000.1.0", "2026.-1.0"):
            with self.assertRaises(release.ReleaseError, msg=bad):
                release.parse_version(bad)

    def test_ordering_is_numeric_date_then_patch_then_prerelease(self) -> None:
        ordered = [
            "2000.1.0", "2026.1.12", "2026.2.0-alpha", "2026.2.0-alpha.1", "2026.2.0-alpha.beta",
            "2026.2.0-beta", "2026.2.0-beta.2", "2026.2.0-beta.11", "2026.2.0-rc.1", "2026.2.0",
            "2026.2.1", "2026.2.10", "2026.9.0", "2026.11.0", "2026.12.0", "2027.1.0",
        ]
        result = sorted(sorted(ordered, reverse=True), key=lambda v: release.parse_version(v).key())
        self.assertEqual(result, ordered)

    def test_only_calver_tags_are_release_tags(self) -> None:
        tags = release.release_tags(["v2026.11.0", "v2026.12.1-rc.1", "v1.0.0", "v2026.11", "v2026.11.0+x", "nightly"])
        self.assertEqual(sorted(tags), ["v2026.11.0", "v2026.12.1-rc.1"])


class PrepareTests(GitCase):
    def test_first_release_uses_root_history_and_preserves_curated_entries(self) -> None:
        write(self.root, "CHANGELOG.md", CHANGELOG.replace(
            "- Curated automation note\n",
            "- Curated automation note\n  with a wrapped detail line\n- first widget\n\n"
            "### Fixed\n\n- Curated fix\n\n### Known issues\n\n- Curated caveat\n",
        ))
        git(self.root, "add", "-A")
        git(self.root, "commit", "-q", "-m", "docs: curate changelog")
        self.commit("feat: first widget")
        self.commit("fix(ui): crash on start")
        self.commit("fix: generated fix")
        self.commit("Tweak the widget")
        self.commit("chore(release): prepare 2026.10.0")
        git(self.root, "checkout", "-q", "-b", "side")
        self.commit("feat: side feature")
        git(self.root, "checkout", "-q", "main")
        git(self.root, "merge", "-q", "--no-ff", "-m", "Merge branch 'side'", "side")
        before_manifest = snapshot(self.root)["Cargo.toml"]

        result = self.prepare(V0, NOV)
        self.assertIsNone(result.previous_tag)
        self.assertEqual(result.changed, ["CHANGELOG.md"])  # initial release already carries this version
        self.assertEqual(snapshot(self.root)["Cargo.toml"], before_manifest)
        text = self.changelog()
        self.assertRegex(text, r"## Unreleased\n\n## 2026\.11\.0 - 2026-11-05\n")
        body = section(text, V0)
        # curated entries survive verbatim and stay ahead of generated ones
        self.assertIn("- Curated automation note\n  with a wrapped detail line\n", body)
        self.assertLess(body.index("- Curated fix"), body.index("generated fix"))
        self.assertIn("### Known issues\n\n- Curated caveat", body)
        # a curated duplicate of a commit subject is not repeated
        self.assertEqual(body.count("first widget"), 1)
        self.assertRegex(body, r"- \*\*ui:\*\* crash on start \([0-9a-f]{7}\)")
        self.assertRegex(body, r"### Other changes\n\n- Tweak the widget \([0-9a-f]{7}\)")
        self.assertIn("side feature", body)
        self.assertIn("initial scaffolding", body)  # first release covers the whole history
        self.assertNotIn("Merge branch", body)
        self.assertNotIn("prepare 2026.10.0", body)
        heads = re.findall(r"(?m)^### (.+)$", body)
        self.assertEqual(heads, ["Added", "Fixed", "Documentation", "Maintenance", "Known issues", "Other changes"])

        self.assertEqual(run_cli(self.root, "validate", "--tag", f"v{V0}")[0], 0)
        self.assertRejected(V0, NOV, "already has a section")

