class PackageTests(GitCase):
    def setUp(self) -> None:
        super().setUp()
        for rel in ("AGENTS.md", "settings.json", "library.sqlite3", "docs/draft.txt", "docs/img/shot.png",
                    "crates/relkit-core/src/lib.rs", "target/release/relkit.d"):
            write(self.root, rel, "excluded private-looking content\n")
        git(self.root, "add", "-A", "-f")
        git(self.root, "commit", "-q", "-m", "chore: add unrelated tracked files")
        self.binary = self.tmp / "bin" / "built-binary"
        self.binary.parent.mkdir()
        self.binary.write_bytes(b"\x7fELF synthetic binary bytes " * 64)
        self.notices = self.tmp / "notices.html"
        self.notices.write_text("<html>synthetic notices</html>\n", encoding="utf-8")
        self.out = self.tmp / "dist"

    def package(self, platform: str, **kw) -> tuple[int, str, str]:
        return run_cli(
            self.root, "package", "--platform", platform, "--binary", str(kw.get("binary", self.binary)),
            "--notices", str(kw.get("notices", self.notices)), "--output", str(kw.get("output", self.out)),
        )

    EXPECTED_DOCS = {"docs/README.md", "docs/guide.md"}

    def test_windows_zip_layout(self) -> None:
        code, _, err = self.package("windows")
        self.assertEqual(code, 0, err)
        archive = self.out / f"animatic-v{V0}-windows-x86_64.zip"
        stem = f"animatic-v{V0}-windows-x86_64"
        with zipfile.ZipFile(archive) as zf:
            names = zf.namelist()
            self.assertEqual(
                set(names),
                {f"{stem}/{n}" for n in {"animatic.exe", "LICENSE", "README.md", "CHANGELOG.md",
                                          "THIRD-PARTY-NOTICES.html", *self.EXPECTED_DOCS}},
            )
            self.assertEqual(len(names), len(set(names)))
            self.assertEqual(zf.read(f"{stem}/animatic.exe"), self.binary.read_bytes())
            self.assertEqual(zf.read(f"{stem}/THIRD-PARTY-NOTICES.html"), self.notices.read_bytes())
            self.assertEqual(zf.read(f"{stem}/docs/guide.md"), (self.root / "docs/guide.md").read_bytes())
            self.assertEqual(zf.read(f"{stem}/CHANGELOG.md"), (self.root / "CHANGELOG.md").read_bytes())
        self.assertEqual([p.name for p in self.out.iterdir()], [archive.name])  # no temp leftovers

    def test_linux_targz_layout_and_modes(self) -> None:
        code, _, err = self.package("linux")
        self.assertEqual(code, 0, err)
        stem = f"animatic-v{V0}-linux-x86_64"
        with tarfile.open(self.out / f"{stem}.tar.gz") as tf:
            members = {m.name: m for m in tf.getmembers()}
            files = {n for n, m in members.items() if m.isfile()}
            self.assertEqual(
                files,
                {f"{stem}/{n}" for n in {"animatic", "LICENSE", "README.md", "CHANGELOG.md",
                                          "THIRD-PARTY-NOTICES.html", *self.EXPECTED_DOCS}},
            )
            for name, member in members.items():
                self.assertTrue(name == stem or name.startswith(stem + "/"), name)
                self.assertEqual((member.uid, member.gid, member.mtime), (0, 0, release.ARCHIVE_EPOCH))
                if member.isdir() or name == f"{stem}/animatic":
                    self.assertEqual(member.mode, 0o755, name)
                else:
                    self.assertEqual(member.mode, 0o644, name)
            self.assertEqual(tf.extractfile(f"{stem}/animatic").read(), self.binary.read_bytes())

    def test_archives_are_reproducible(self) -> None:
        self.package("windows")
        self.package("linux")
        first = {p.name: p.read_bytes() for p in self.out.iterdir()}
        for path in [self.binary, self.notices, *(self.root / "docs").glob("*.md")]:
            os.utime(path, (1_900_000_000, 1_900_000_000))
        second_out = self.tmp / "dist2"
        self.package("windows", output=second_out)
        self.package("linux", output=second_out)
        self.assertEqual({p.name: p.read_bytes() for p in second_out.iterdir()}, first)

    def test_untracked_ignored_and_private_docs_are_never_shipped(self) -> None:
        write(self.root, ".gitignore", "docs/ignored.md\n")
        write(self.root, "docs/private.md", "private notes\n")  # untracked, not ignored
        write(self.root, "docs/ignored.md", "ignored notes\n")
        write(self.root, "docs/staged-later.md", "not added\n")
        for platform in ("windows", "linux"):
            self.assertEqual(self.package(platform)[0], 0)
        with zipfile.ZipFile(self.out / f"animatic-v{V0}-windows-x86_64.zip") as zf:
            names = {n.split("/", 1)[1] for n in zf.namelist()}
            payload = b"".join(zf.read(n) for n in zf.namelist())
        with tarfile.open(self.out / f"animatic-v{V0}-linux-x86_64.tar.gz") as tf:
            tar_names = {m.name.split("/", 1)[1] for m in tf.getmembers() if m.isfile()}
        for found in (names, tar_names):
            self.assertEqual({n for n in found if n.startswith("docs/")}, self.EXPECTED_DOCS)
